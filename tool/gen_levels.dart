// Generates solvable handmade levels by playing backwards from one peg.
// Run: dart run tool/gen_levels.dart > lib/game/levels_data.dart
// ignore_for_file: avoid_print
import 'dart:io';
import 'dart:math';
import 'package:hopstone/game/board_def.dart';
import 'package:hopstone/game/catalog_data.dart';

/// Reverse moves of the last successful [generate] call (to, over, from).
final lastReverse = <(Pos, Pos, Pos)>[];

List<Pos>? generate(Set<Pos> holes, List<(int, int)> dirs, int pegs, Random rnd) {
  final rev = <(Pos, Pos, Pos)>[];
  final cur = <Pos>{holes.elementAt(rnd.nextInt(holes.length))};
  while (cur.length < pegs) {
    final opts = <(Pos, Pos, Pos)>[];
    for (final to in cur) {
      for (final (dr, dc) in dirs) {
        final over = Pos(to.row - dr, to.col - dc);
        final from = Pos(to.row - 2 * dr, to.col - 2 * dc);
        if (holes.contains(over) && holes.contains(from) &&
            !cur.contains(over) && !cur.contains(from)) {
          opts.add((to, over, from));
        }
      }
    }
    if (opts.isEmpty) return null;
    final (to, over, from) = opts[rnd.nextInt(opts.length)];
    cur..remove(to)..add(over)..add(from);
    rev.add((to, over, from));
  }
  lastReverse
    ..clear()
    ..addAll(rev);
  return cur.toList()
    ..sort((a, b) => a.row != b.row ? a.row - b.row : a.col - b.col);
}

void main() {
  print('// GENERATED by tool/gen_levels.dart - do not edit by hand.');
  print('// Each entry is a start position (row, col) that can be cleared to one peg.');
  print("import 'board_def.dart';\n");
  print('final List<BoardDef> handmadeLevels = [');
  // Shape and size ramp for every pack of every world (20 worlds x 4 packs).
  const maxPegs = {
    BoardShape.english: 30, BoardShape.french: 31, BoardShape.triangle: 9, BoardShape.square: 14,
    BoardShape.diamond: 19, BoardShape.ring: 33, BoardShape.heart: 20, BoardShape.hourglass: 24,
    BoardShape.arrow: 17, BoardShape.tee: 17, BoardShape.stairs: 15,
  };
  const pool = [
    BoardShape.english, BoardShape.square, BoardShape.diamond, BoardShape.french, BoardShape.hourglass,
    BoardShape.heart, BoardShape.ring, BoardShape.tee, BoardShape.arrow, BoardShape.stairs, BoardShape.triangle,
  ];
  final packs = <(String, String, Difficulty, BoardShape, List<int>)>[];
  // One smooth ramp over all 400 levels: 4 pegs at the start, ~30 at the end.
  int target(int g) => (4 + 26 * pow(g / 399, 0.75)).round();
  for (var w = 0; w < worldCatalog.length; w++) {
    for (var p = 0; p < 4; p++) {
      final name = worldCatalog[w].packs[p];
      final first = (w * 4 + p) * 5;
      final counts = [for (var i = 0; i < 5; i++) target(first + i)];
      // shapes that can actually hold that many pegs, rotated for variety
      final fits = pool.where((s) => maxPegs[s]! >= counts.last + 1).toList();
      final shape = w == 0 ? BoardShape.english : fits[(w * 4 + p) % fits.length];
      final level = (w * 4 + p) / 79;
      final d = level < 0.2 ? Difficulty.easy : level < 0.5 ? Difficulty.medium : level < 0.8 ? Difficulty.hard : Difficulty.expert;
      packs.add((name.toLowerCase(), name, d, shape, counts));
    }
  }
  final used = <String>{};
  final solFile = Platform.environment['HOP_SOLUTIONS'];
  final solutions = solFile == null ? null : StringBuffer();
  for (final (id, name, d, shape, counts) in packs) {
    final holes = shapeHoles(shape);
    final dirs = shape == BoardShape.triangle ? triangular : orthogonal;
    for (var i = 0; i < counts.length; i++) {
      final rnd = Random(1000 * counts[i] + 7 + shape.index + i * 131 + id.codeUnits.fold(0, (a, b) => a + b));
      List<Pos>? res;
      var want = counts[i];
      while (res == null && want > 3) {
        for (var tries = 0; res == null && tries < 3000; tries++) {
          final cand = generate(holes, dirs, want, rnd);
          if (cand == null) continue;
          final key = '${shape.name}:${cand.map((p) => '${p.row}.${p.col}').join(',')}';
          if (used.add(key)) res = cand;
        }
        if (res == null) {
          stderr.writeln('$id ${i + 1}: $want pegs not reachable, trying ${want - 1}');
          want--;
        }
      }
      if (res == null) throw StateError('cannot build $id ${i + 1}');
      final lit = res.map((p) => '(${p.row}, ${p.col})').join(', ');
      // forward solution = the reverse moves played backwards
      solutions?.writeln('$id-${i + 1}: ${lastReverse.reversed.map((m) => '${m.$3.row},${m.$3.col}>${m.$2.row},${m.$2.col}>${m.$1.row},${m.$1.col}').join(' ')}');
      print("  levelBoard('$id-${i + 1}', '$name ${i + 1}', Difficulty.${d.name}, BoardShape.${shape.name}, [$lit]),");
    }
  }
  print('];');
  if (solFile != null) File(solFile).writeAsStringSync(solutions.toString());
}
